-- 1. Buat tabel leaderboard
create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  player_name text not null,
  score integer not null,
  level integer default 1,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Index untuk mempercepat query ranking berdasarkan score tertinggi
create index if not exists idx_leaderboard_score on public.leaderboard (score desc);

-- 3. Aktifkan Row Level Security (RLS)
alter table public.leaderboard enable row level security;

-- 4. Beri akses publik untuk membaca data ranking (SELECT)
create policy "Allow public read" on public.leaderboard
  for select
  using (true);

-- 5. Beri akses publik untuk mengirimkan skor baru (INSERT)
create policy "Allow public insert" on public.leaderboard
  for insert
  with check (true);
